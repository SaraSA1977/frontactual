  filterProducts() {
    return this.products.filter(p => {
      const matchesCategory = this.selectedCategory === 'Todos' || 
        (this.selectedCategory === 'Favoritos' ? p.favorite : p.category === this.selectedCategory);
      const matchesSubcategory = this.selectedSubcategory === 'Todas' || p.family === this.selectedSubcategory;
      const matchesSearch = !this.searchText || 
        p.name.toLowerCase().includes(this.searchText.toLowerCase()) ||
        p.generic_name.toLowerCase().includes(this.searchText.toLowerCase());
      return matchesCategory && matchesSubcategory && matchesSearch;
    });
  }

